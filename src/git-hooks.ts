const STATE = ".docnexus/.runtime/git-merge.json";
const MERGE_LOG = ".docnexus/.runtime/git-merge.log";
const MERGE_LOG_PREVIOUS = `${MERGE_LOG}.1`;
const MERGE_LOG_MAX_BYTES = 64 * 1024;
const NOTICE = "<!-- Generated by docnexus; do not edit. Regenerated after every memory change. -->";
const MARKER = "# DocNexus Git hooks v1";
const hooks = { "post-index-change": "index", "pre-commit": "check" } as const;
interface MergeState { version: 1; ours: string; theirs?: string; entries: GitIndexEntry[]; done?: string }
const posix = (path: string) => path.split(sep).join("/");
const signature = (entries: GitIndexEntry[]) => sha256(stableJson(entries));
const fail = (message: string) => new DocNexusError("git_merge_not_ready", message);
const integrity = (message: string, id?: string) => new DocNexusError("text_integrity_error", message, undefined,
  id ? { command: ["document", "sync", "--id", id] } : undefined);

async function changedKnowledge(context: GitContext, indexFile = context.index): Promise<string[]> {
  return (await runWorkspaceGit(context.repository, ["diff", "--cached", "--no-relative", "--no-renames", "--name-only", "-z"], { indexFile }))
    .split("\0").filter(path => /^(library\/|records\/)/.test(knowledgePath(context, path) ?? ""));
}

async function unsupportedOperation(context: GitContext): Promise<string | undefined> {
  for (const [name, operation] of [["rebase-merge", "rebase"], ["rebase-apply", "rebase/am"], ["CHERRY_PICK_HEAD", "cherry-pick"], ["REVERT_HEAD", "revert"]]) {
    if (await lstat(join(dirname(context.mergeHeadPath), name)).then(() => true, (error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return false;
      throw error;
    })) return operation;
  }
  return undefined;
}

async function rejectUnsupported(root: string, operation: string): Promise<never> {
  await assertNoSymbolicLinks(root, STATE);
  await rm(join(root, STATE), { force: true });
  throw new DocNexusError("git_merge_unsupported", `automatic document merge repair does not support ${operation}; preserve the document units and use manual document-level recovery. No document assets were modified.`);
}

async function readState(root: string): Promise<MergeState | undefined> {
  await assertNoSymbolicLinks(root, STATE);
  const text = await readIfExists(join(root, STATE));
  if (text === undefined) return undefined;
  const state = JSON.parse(text) as MergeState;
  if (state.version !== 1 || !/^[a-f0-9]{40}(?:[a-f0-9]{24})?$/.test(state.ours)
    || (state.theirs !== undefined && !/^[a-f0-9]{40}(?:[a-f0-9]{24})?$/.test(state.theirs))
    || !Array.isArray(state.entries) || state.entries.some(entry => !entry || typeof entry.path !== "string"
      || !/^[a-f0-9]{40}(?:[a-f0-9]{24})?$/.test(entry.oid) || !/^[0-7]{6}$/.test(entry.mode) || ![1, 2, 3].includes(entry.stage))) throw fail(`invalid ${STATE}; preserve and inspect the saved merge context`);
  return state;
}

async function saveState(root: string, state: MergeState): Promise<void> {
  await assertNoSymbolicLinks(root, STATE);
  await ensureIgnoredEntries(root, [".runtime/"]);
  await atomicWrite(join(root, STATE), `${JSON.stringify(state, null, 2)}\n`);
}

/** Capture both unresolved stages and Git's resolve-undo stages, tied to these parents. */
async function capture(root: string, context: GitContext, indexFile = context.index): Promise<MergeState | undefined> {
  const current = parseIndexEntries(await runWorkspaceGit(context.repository, ["ls-files", "--full-name", "--unmerged", "-z"], { indexFile }))
    .filter(entry => knowledgePath(context, entry.path));
  const parents = await mergeParents(context);
  const operation = !parents && await unsupportedOperation(context);
  if (operation && (current.length || (await changedKnowledge(context, indexFile)).length)) return rejectUnsupported(root, operation);
  const previous = await readState(root);
  if (previous?.entries.some(entry => !knowledgePath(context, entry.path))) throw fail("saved conflict paths do not match this knowledge output; preserve and inspect the merge context");
  if (!parents) {
    // Git can write the conflicted index before publishing MERGE_HEAD.
    if (current.length) {
      const ours = (await runWorkspaceGit(context.repository, ["rev-parse", "HEAD"])).trim();
      const state: MergeState = { version: 1, ours, entries: current };
      await saveState(root, state);
      return state;
    }
    if (previous) await rm(join(root, STATE));
    return undefined;
  }
  const undo = parseIndexEntries(await runWorkspaceGit(context.repository, ["ls-files", "--full-name", "--resolve-undo", "-z"], { indexFile }))
    .filter(entry => knowledgePath(context, entry.path));
  const candidates = new Map<string, GitIndexEntry[]>();
  for (const entry of [...(previous?.ours === parents.ours && (!previous.theirs || previous.theirs === parents.theirs) ? previous.entries : []), ...undo]) {
    const list = candidates.get(entry.path) ?? [];
    const index = list.findIndex(value => value.stage === entry.stage);
    if (index < 0) list.push(entry); else list[index] = entry;
    candidates.set(entry.path, list);
  }
  const retained = (await mapWithConcurrency([...candidates], 24, async ([path, stages]) => {
    let matches = true;
    for (const [stage, commit] of [[2, parents.ours], [3, parents.theirs]] as const) {
      const tree = await runWorkspaceGit(context.repository, ["ls-tree", "-z", commit, "--", path]);
      const entry = /^(\d+) blob ([a-f0-9]+)\t/.exec(tree);
      const expected = stages.find(value => value.stage === stage);
      if ((entry?.[2] ?? undefined) !== expected?.oid || (entry?.[1] ?? undefined) !== expected?.mode) matches = false;
    }
    return matches ? stages : [];
  })).flat();
  const byStage = new Map([...retained, ...current].map(entry => [`${entry.path}\0${entry.stage}`, entry]));
  const entries = [...byStage.values()].sort((a, b) => a.path.localeCompare(b.path) || a.stage - b.stage);
  if (!entries.length) return undefined;
  const same = previous?.ours === parents.ours && previous.theirs === parents.theirs;
  const state: MergeState = { version: 1, ...parents, entries, ...(same && previous.done ? { done: previous.done } : {}) };
  await saveState(root, state);
  return state;
}

function mergeSnapshot(root: string, context: GitContext, state: MergeState, index: Awaited<ReturnType<typeof readIndex>>) {
  const recordIds = [...new Set(index.entries.flatMap(entry => {
    const match = /^records\/(doc_[a-f0-9]{16})\//.exec(knowledgePath(context, entry.path)!);
    return match ? [match[1]] : [];
  }))].sort();
  return { conflicts: [...new Set(state.entries.map(entry => entry.path))], recordIds,
    read: async (path: string) => {
      const repoPath = posix(relative(context.repository, join(root, path)));
      const content = index.staged.get(repoPath);
      if (content === undefined) throw fail(`resolve and stage ${repoPath} before automatic sync`);
      return content;
    } };
}

async function guardWorktree(root: string, context: GitContext, index: Awaited<ReturnType<typeof readIndex>>, overwrites: Set<string>) {
  await mapWithConcurrency([...index.staged], 24, async ([path, content]) => {
    if (overwrites.has(path) && path.endsWith("/record.json")) return;
    const projectPath = relative(root, join(context.repository, path));
    await assertNoSymbolicLinks(root, projectPath);
    if (await readIfExists(join(context.repository, path)) !== content) throw fail(`unstaged edits in ${path}; stage the reviewed contents or preserve those edits before retrying`);
  });
  // Untracked records must never be admitted by navigation's filesystem reader.
  const known = new Set(index.entries.flatMap(entry => /^records\/(doc_[a-f0-9]{16})\//.exec(knowledgePath(context, entry.path)!)?.[1] ?? []));
  const directory = join(workspacePath(root), "records");
  await assertNoSymbolicLinks(root, relative(root, directory));
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.isSymbolicLink() || (entry.isDirectory() && !known.has(entry.name))) throw fail(`untracked or symlinked record directory ${entry.name}; preserve it before automatic sync`);
  }
  const untracked = (await runWorkspaceGit(context.repository, ["ls-files", "--others", "--full-name", "-z", "--", `${context.prefix}concepts/`, `${context.prefix}CONCEPTS.md`])).split("\0").filter(Boolean);
  for (const path of untracked) {
    if (path.endsWith(".md")) throw fail(`untracked navigation file ${path}; preserve or stage it before automatic sync`);
  }
}

/** Atomically publish a replacement index while Git's own lock excludes other writers. */
async function repair(root: string, context: GitContext): Promise<string> {
  await assertNoSymbolicLinks(dirname(context.index), relative(dirname(context.index), context.index));
  await assertNoSymbolicLinks(dirname(context.index), relative(dirname(context.index), `${context.index}.lock`));
  const lockedIndex = `${context.index}.lock`;
  const handle = await open(lockedIndex, "wx", 0o600).catch((error: NodeJS.ErrnoException) => {
    if (error.code === "EEXIST") return undefined;
    throw error;
  });
  if (!handle) return "busy";
  let published = false;
  try {
    await handle.writeFile(await readFile(context.index));
    await handle.sync();
    await handle.close();
    return await withProjectLock(root, async () => {
      const parents = await mergeParents(context);
      const state = await readState(root);
      if (!parents || !state?.theirs || state.ours !== parents.ours || state.theirs !== parents.theirs) return "idle";
      const index = await readIndex(context, lockedIndex);
      if (state.done === signature(index.entries)) return "ready";
      if (index.entries.some(entry => entry.stage !== 0 && !generatedPath(context, entry.path))) return "waiting";
      const prepared = await prepareGitMerge(root, mergeSnapshot(root, context, state, index));
      const overwrites = new Set([...prepared.files.keys()].map(path => posix(relative(context.repository, path))));
      await guardWorktree(root, context, index, overwrites);
      delete state.done;
      await saveState(root, state);
      await commitTextTransaction(root, prepared.files, { gitMerge: true });
      const outputs = new Map(prepared.files);
      const modes = new Map(index.entries.map(entry => [entry.path, entry.mode]));
      const navigation = renderConceptFiles(await buildConceptIndex(root), root);
      for (const [path, content] of navigation) outputs.set(join(workspacePath(root), path), content);
      for (const entry of index.entries) {
        const local = knowledgePath(context, entry.path)!;
        if (local.startsWith("concepts/") && index.blobs.get(entry.oid)!.includes(NOTICE) && !navigation.has(local)
          && await readIfExists(join(context.repository, entry.path)) === undefined) outputs.set(join(context.repository, entry.path), null);
      }
      const updates: string[] = [];
      for (const [absolute, content] of outputs) {
        const path = posix(relative(context.repository, absolute));
        if (!knowledgePath(context, path)) throw fail(`automatic staging refused unexpected path ${path}`);
        await assertNoSymbolicLinks(root, relative(root, absolute));
        if ((await readIfExists(absolute)) !== (content ?? undefined)) throw fail(`generated file changed while staging: ${path}; review and stage it to retry`);
        const zero = "0".repeat(parents.ours.length);
        updates.push(`0 ${zero}\t${path}\0`);
        if (content !== null) {
          const oid = (await runWorkspaceGit(context.repository, ["hash-object", "-w", "--no-filters", "--stdin"], { input: content })).trim();
          const mode = modes.get(path) ?? "100644";
          updates.push(`${mode} ${oid}\t${path}\0`);
        }
      }
      await runWorkspaceGit(context.repository, ["update-index", "-z", "--index-info"], { indexFile: lockedIndex, input: updates.join("") });
      const next = await readIndex(context, lockedIndex);
      await validateStagedKnowledge(root, context, next);
      const actualParents = await mergeParents(context);
      if (!actualParents || actualParents.ours !== parents.ours || actualParents.theirs !== parents.theirs) throw fail("Git merge changed during automatic repair; preserve generated contents and inspect the merge");
      state.done = signature(next.entries);
      await saveState(root, state);
      await rename(lockedIndex, context.index);
      published = true;
      await syncDirectory(dirname(context.index));
      process.stderr.write(`docnexus: ${prepared.result.count} conflicted document(s) synced and generated files staged; review the diff, then commit.\n`);
      return "ready";
    }, 30_000, { rejectPendingTransaction: true });
  } finally {
    await handle.close().catch(() => {});
    if (!published) await rm(lockedIndex, { force: true });
  }
}

async function validateStagedKnowledge(root: string, context: GitContext, index: Awaited<ReturnType<typeof readIndex>>, scope?: ReadonlySet<string>) {
  const error = scope ? integrity : fail;
  if (index.entries.some(entry => entry.stage !== 0)) throw error("knowledge still has unresolved index entries; resolve and stage the affected document units before committing");
  const documents: KnowledgeDocument[] = [];
  const documentIds = new Set<string>();
  const paths = new Set<string>();
  const get = (path: string) => {
    const content = index.staged.get(`${context.prefix}${path}`);
    if (content === undefined) throw error(`missing staged asset ${path}`);
    return content;
  };
  for (const entry of index.entries) {
    const local = knowledgePath(context, entry.path)!;
    const match = /^records\/(doc_[a-f0-9]{16})\/record\.json$/.exec(local);
    if (!match || (scope && !scope.has(match[1]))) continue;
    const record = await parseRecordFile(root, match[1], get(local));
    if (paths.has(record.file_path)) throw error(`duplicate staged document path ${record.file_path}`);
    paths.add(record.file_path);
    let metadata: unknown;
    try { metadata = JSON.parse(get(`records/${record.id}/metadata.json`)); }
    catch { throw error(`invalid staged metadata.json for ${record.id}; restore or review the document unit`); }
    assertValidMetadata(metadata);
    const document = get(`library/${record.file_path}`);
    if (metadata.title !== record.title || sha256(stableJson(metadata)) !== record.metadata_hash
      || sha256(get(`records/${record.id}/source.md`)) !== record.source_hash || sha256(get(`records/${record.id}/timeline.md`)) !== record.timeline_hash) throw error(`staged metadata, source or timeline do not match record ${record.id}; restore the stored assets or use the reviewed capture workflow, then stage the complete document unit`);
    if (sha256(factDocumentTemplate(document)) !== record.document_hash) {
      if (scope) throw integrity(`unadopted library edit: ${record.file_path}; review it, run docnexus document sync --id ${record.id}, then stage the synced document unit`, record.id);
      throw fail(`staged assets do not match record ${record.id}; review and stage the synced document unit before committing`);
    }
    documents.push({ id: record.id, file_path: record.file_path, document, metadata });
    documentIds.add(record.id);
  }
  for (const entry of index.entries) {
    const local = knowledgePath(context, entry.path)!;
    const asset = /^records\/(doc_[a-f0-9]{16})\//.exec(local);
    if (asset && (!scope || scope.has(asset[1])) && !documentIds.has(asset[1])) throw error(`staged record ${asset[1]} is incomplete`);
  }
  if (scope) return documents;
  const knowledge = resolveKnowledge(documents);
  for (const document of documents) renderFactDocument(document.document!, knowledge.facts);
  return documents;
}

/** Hash only affected units; global reads are limited to semantic dependencies. */
async function validateChangedKnowledge(root: string, context: GitContext, changed: string[], indexFile: string) {
  const local = (path: string) => knowledgePath(context, path)!;
  const recordId = (path: string) => /^records\/(doc_[a-f0-9]{16})\//.exec(local(path))?.[1];
  const changedIds = new Set(changed.flatMap(path => recordId(path) ?? []));
  const changedBodies = new Set(changed.flatMap(path => {
    const value = local(path);
    return value.startsWith("library/") ? [value.slice("library/".length)] : [];
  }));
  // The changed record identifies both the document and its library body; no
  // full catalog is needed when every changed body is covered this way.
  const records = new Map<string, { file_path: string }>();
  const remember = (id: string, raw: string) => {
    let record: { file_path?: unknown };
    try { record = JSON.parse(raw); }
    catch { throw integrity(`invalid staged record ${id}; inspect the document unit before committing`); }
    if (typeof record.file_path !== "string") throw integrity(`invalid staged record ${id}; missing file_path`);
    records.set(id, { file_path: record.file_path });
  };
  const changedRecords = await readIndex(context, indexFile, entry =>
    entry.stage === 0 && local(entry.path).endsWith("/record.json") && changedIds.has(recordId(entry.path)!));
  for (const entry of changedRecords.entries) remember(recordId(entry.path)!, changedRecords.staged.get(entry.path)!);
  const scope = new Set(changedIds);
  const matchedBodies = new Set<string>();
  for (const [id, record] of records) if (changedBodies.has(record.file_path)) {
    scope.add(id);
    matchedBodies.add(record.file_path);
  }
  // A library-only conflict (branch committed before hooks were installed, or
  // record.json resolved to an unchanged side) has no record path to learn the
  // id from. Fall back to the full catalog only for that rare case.
  let catalog: Awaited<ReturnType<typeof readIndex>> | undefined;
  const loadCatalog = async () => {
    if (catalog) return catalog;
    catalog = await readIndex(context, indexFile, entry => entry.stage === 0 && /\/record\.json$/.test(entry.path));
    for (const entry of catalog.entries) {
      const id = recordId(entry.path)!;
      if (records.has(id)) continue;
      try {
        const record = JSON.parse(catalog.staged.get(entry.path)!);
        if (typeof record?.file_path === "string") records.set(id, { file_path: record.file_path });
      } catch { /* An unrelated damaged record does not gate a plain prose commit. */ }
    }
    return catalog;
  };
  if ([...changedBodies].some(body => !matchedBodies.has(body))) {
    await loadCatalog();
    for (const [id, record] of records) if (changedBodies.has(record.file_path)) {
      scope.add(id);
      matchedBodies.add(record.file_path);
    }
  }
  const paths = new Set([...scope].flatMap(id => records.has(id) ? [`library/${records.get(id)!.file_path}`] : []));
  for (const [id, record] of records) if (paths.has(`library/${record.file_path}`) && !scope.has(id)) throw integrity(`duplicate staged document path ${record.file_path}`);
  const scoped = await readIndex(context, indexFile, entry => {
    const value = local(entry.path);
    const asset = /^records\/(doc_[a-f0-9]{16})\//.exec(value);
    return asset ? scope.has(asset[1]) : paths.has(value);
  });
  const documents = await validateStagedKnowledge(root, context, scoped, scope);
  const additionsOrDeletes = (await runWorkspaceGit(context.repository, ["diff", "--cached", "--no-relative", "--no-renames", "--diff-filter=AD", "--name-only", "-z"], { indexFile }))
    .split("\0").some(path => /^(library\/|records\/)/.test(knowledgePath(context, path) ?? ""));
  let graphChanged = additionsOrDeletes;
  const changedMetadata = changed.filter(path => path.endsWith("/metadata.json"));
  if (!graphChanged && changedMetadata.length) {
    const tree = await runWorkspaceGit(context.repository, ["ls-tree", "-r", "-z", "HEAD", "--", `${context.prefix}records/`]);
    const previous = new Map(tree.split("\0").flatMap(line => {
      const match = /^\d+ blob ([a-f0-9]+)\t([\s\S]+)$/.exec(line);
      return match ? [[match[2], match[1]]] : [];
    }));
    const blobs = await readGitBlobs(context.repository, changedMetadata.flatMap(path => previous.has(path) ? [previous.get(path)!] : []));
    const graph = (value: { entities?: unknown; relationships?: unknown; facts?: unknown }) => stableJson({ entities: value.entities, relationships: value.relationships, facts: value.facts ?? [] });
    graphChanged = changedMetadata.some(path => {
      try { return graph(JSON.parse(blobs.get(previous.get(path)!)!)) !== graph(JSON.parse(scoped.staged.get(path)!)); }
      catch { return true; } // A repaired/unknown prior schema needs full semantic validation.
    });
  }
  if (!graphChanged && !documents.some(document => factReferenceIds(document.document!).length)) return documents.length;
  const all = await loadCatalog();
  const semantic = await readIndex(context, indexFile, entry => {
    const local = knowledgePath(context, entry.path)!;
    return local.endsWith("/metadata.json") || (graphChanged && local.startsWith("library/"));
  });
  if (records.size !== all.entries.length) throw integrity("cannot validate cross-document dependencies with malformed staged records; inspect the affected records");
  const prospective: KnowledgeDocument[] = [];
  for (const [id, record] of records) {
    const raw = semantic.staged.get(`${context.prefix}records/${id}/metadata.json`);
    if (raw === undefined) throw integrity(`missing staged metadata for ${id}`);
    let metadata: unknown;
    try { metadata = JSON.parse(raw); }
    catch { throw integrity(`invalid staged metadata for ${id}; cross-document dependencies cannot be checked`); }
    assertValidMetadata(metadata);
    const document = graphChanged ? semantic.staged.get(`${context.prefix}library/${record.file_path}`) : undefined;
    if (graphChanged && document === undefined) throw integrity(`missing staged library document ${record.file_path}`);
    prospective.push({ id, file_path: record.file_path, metadata, document });
  }
  const knowledge = resolveKnowledge(prospective);
  for (const document of graphChanged ? prospective : documents) renderFactDocument(document.document!, knowledge.facts);
  return documents.length;
}

const logLine = (log: Awaited<ReturnType<typeof openMergeLog>>, message: string) =>
  log.write(`[${new Date().toISOString()}] ${message}\n`);

/** Open the worker log, keeping at most one previous file once it reaches 64 KiB. */
async function openMergeLog(root: string, rotate = true) {
  await assertNoSymbolicLinks(root, MERGE_LOG);
  await assertNoSymbolicLinks(root, MERGE_LOG_PREVIOUS);
  const path = join(root, MERGE_LOG);
  await mkdir(dirname(path), { recursive: true });
  const size = await stat(path).then(info => info.size, (error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return 0;
    throw error;
  });
  // A file still open in another worker can resist the rename (notably on
  // Windows); keep appending instead of truncating that worker's diagnostics.
  let rotated = false;
  if (rotate && size >= MERGE_LOG_MAX_BYTES) {
    await rm(join(root, MERGE_LOG_PREVIOUS), { force: true }).catch(() => undefined);
    rotated = await rename(path, join(root, MERGE_LOG_PREVIOUS)).then(() => true, () => false);
    if (rotated) await syncDirectory(dirname(path));
  }
  const log = await open(path, "a", 0o600);
  if (rotated) await logLine(log, `log rotated; previous entries in ${MERGE_LOG_PREVIOUS}`);
  return log;
}

async function runMergeWorker(root: string, context: GitContext, note: (message: string) => Promise<unknown>) {
  let waitingFor = "index";
  for (let attempt = 0; attempt < 100; attempt++) {
    const operation = await unsupportedOperation(context);
    if (operation) return rejectUnsupported(root, operation);
    if (await lstat(`${context.index}.lock`).then(() => true, (error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return false;
      throw error;
    })) { waitingFor = "index"; await setTimeout(50); continue; }
    const state = await withProjectLock(root, () => capture(root, context), 30_000, { rejectPendingTransaction: true });
    if (!state) return { status: "idle" };
    if (!state.theirs) {
      if (waitingFor !== "merge") await note("waiting for MERGE_HEAD");
      waitingFor = "merge";
      await setTimeout(50);
      continue;
    }
    const status = await repair(root, context);
    if (status !== "busy") return { status };
    waitingFor = "index";
    await setTimeout(50);
  }
  if (waitingFor === "merge") return withProjectLock(root, () => rejectUnsupported(root, "an unresolved index without MERGE_HEAD"), 30_000, { rejectPendingTransaction: true });
  throw fail("Git index stayed busy; stage reviewed contents again to retry automatic repair");
}

async function scheduleWorker(root: string) {
  // The worker rotates before writing; the parent only needs a valid stderr fd.
  const log = await openMergeLog(root, false);
  try {
    const env = {
      ...Object.fromEntries(Object.entries(process.env).filter(([key]) => !key.startsWith("GIT_") && key !== "DOCNEXUS_GIT_INTERNAL")),
      DOCNEXUS_GIT_WORKER: "1"
    };
    const child = spawn(process.execPath, [fileURLToPath(new URL("./cli.js", import.meta.url)), "--project-root", root, "git", "hook", "worker"], {
      detached: true, stdio: ["ignore", "ignore", log.fd], env
    });
    child.on("error", error => process.stderr.write(`docnexus: cannot start merge worker: ${error.message}\n`));
    child.unref();
    process.stderr.write(`docnexus: automatic repair queued; wait for generated records to be staged before committing. Details: ${MERGE_LOG}\n`);
  } finally { await log.close(); }
}

export async function runGitHook(projectRoot: string, action: string) {
  const root = await realpath(projectRoot);
  const context = await gitContext(root);
  if (process.env.DOCNEXUS_GIT_HOOK && await realpath(process.cwd()) !== context.repository) return { status: "ignored_other_worktree" };
  const callerIndex = process.env.GIT_INDEX_FILE && resolve(context.repository, process.env.GIT_INDEX_FILE);
  if (action === "check") {
    const indexFile = callerIndex || context.index;
    const changed = await changedKnowledge(context, indexFile);
    const parents = await mergeParents(context);
    if (!changed.length && !parents) return { status: "skipped", reason: "no_knowledge_changes" };
    const operation = await unsupportedOperation(context);
    if (operation) return rejectUnsupported(root, operation);
    if (parents && indexFile !== context.index) throw fail("finish and stage the merge using the normal index before committing; alternate-index merge commits are unsupported");
    return withProjectLock(root, async () => {
      const state = await capture(root, context, indexFile);
      if (state?.theirs) {
        const entries = await readIndexEntries(context, indexFile);
        if (state.done !== signature(entries)) throw fail("automatic merge repair has not finished for this staged version; stage the reviewed contents and wait for the ready message before committing");
        // These exact Git objects were fully validated before index publication.
        return { status: "verified", cached: true };
      }
      if (!changed.length) return { status: "skipped", reason: "no_knowledge_changes" };
      return { status: "verified", checked_documents: await validateChangedKnowledge(root, context, changed, indexFile) };
    }, 30_000, { rejectPendingTransaction: true });
  }
  // Capture/repair never redirects writes into an alternate or partial index.
  if (callerIndex && callerIndex !== context.index) return { status: "ignored_alternate_index" };
  // Reject before acquiring a project lease: a rebase may have a detached HEAD,
  // and no canonical document operation should run just to report its kind.
  const operation = await unsupportedOperation(context);
  if (operation) return rejectUnsupported(root, operation);
  if (action === "worker") {
    const log = await openMergeLog(root);
    const note = (message: string) => logLine(log, message);
    await note(`worker start pid=${process.pid}`);
    try {
      const result = await runMergeWorker(root, context, note);
      await note(`worker done status=${result.status}`);
      return result;
    } catch (error) {
      const failure = asDocNexusError(error);
      await note(`worker failed ${failure.code}: ${failure.message.replace(/\s+/g, " ")}`);
      // A detached worker reports through this log; an interactive caller still
      // receives the original error.
      if (process.env.DOCNEXUS_GIT_WORKER === "1") {
        process.exitCode = 1;
        return { status: "failed", code: failure.code };
      }
      throw error;
    } finally {
      await log.close();
    }
  }
  if (action !== "index") throw new DocNexusError("invalid_params", "unknown Git hook action");
  const state = await withProjectLock(root, async () => {
    // read-cache can call the hook after closing a complete index.lock but
    // before publishing it. Capture that snapshot; repair only after unlock.
    let indexFile = context.index;
    await assertNoSymbolicLinks(dirname(context.index), relative(dirname(context.index), `${context.index}.lock`));
    if (await lstat(`${context.index}.lock`).then(info => info.isFile(), (error: NodeJS.ErrnoException) => {
      if (error.code === "ENOENT") return false;
      throw error;
    })) indexFile = `${context.index}.lock`;
    try { return await capture(root, context, indexFile); }
    catch (error) {
      // A different Git writer may have acquired a new, incomplete lock after
      // the triggering command published its own index. Keep the valid index.
      if (indexFile !== context.index && error instanceof DocNexusError && error.code === "git_operation_failed") return capture(root, context);
      throw error;
    }
  }, 30_000, { rejectPendingTransaction: true });
  if (!state) return { status: "idle" };
  if (!state.theirs) {
    await scheduleWorker(root);
    return { status: "captured" };
  }
  const status = await repair(root, context);
  if (status === "busy") await scheduleWorker(root);
  return { status };
}

const quote = (value: string) => `'${(process.platform === "win32" ? value.replaceAll("\\", "/") : value).replaceAll("'", "'\\''")}'`;

export async function manageGitHooks(projectRoot: string, action: string) {
  return withProjectLock(projectRoot, async () => {
    const root = await realpath(projectRoot);
    const { requireInitializedProject } = await import("./project.js");
    await requireInitializedProject(root);
    const context = await gitContext(root);
    const directory = resolve(context.repository, (await runWorkspaceGit(context.repository, ["rev-parse", "--path-format=absolute", "--git-path", "hooks"])).trim());
    const common = resolve(context.repository, (await runWorkspaceGit(context.repository, ["rev-parse", "--path-format=absolute", "--git-common-dir"])).trim());
    if (directory !== join(common, "hooks")) throw new DocNexusError("git_operation_failed", "custom core.hooksPath is not modified automatically; integrate DocNexus hook commands into that hook manager explicitly");
    await assertNoSymbolicLinks(common, relative(common, directory));
    const projectRelative = posix(relative(context.repository, root)) || ".";
    const cliRelative = posix(relative(root, fileURLToPath(new URL("./cli.js", import.meta.url))));
    const runtimeRelative = !isAbsolute(cliRelative) && cliRelative !== ".." && !cliRelative.startsWith("../") ? cliRelative : "";
    const owner = `# Project: ${JSON.stringify(projectRelative)}`;
    const items = [];
    for (const [name, event] of Object.entries(hooks)) {
      const path = join(directory, name);
      const backup = `${path}.docnexus-original`;
      for (const file of [path, backup]) await assertNoSymbolicLinks(common, relative(common, file));
      const existing = await readIfExists(path);
      const managed = existing?.includes(MARKER) === true;
      if (managed && !existing?.includes(owner)) {
        const oldOwner = /^# Project: (.+)$/m.exec(existing!)?.[1];
        const oldRoot: unknown = oldOwner && JSON.parse(oldOwner);
        if (typeof oldRoot !== "string" || (resolve(context.repository, oldRoot) !== root
          && await readIfExists(join(resolve(context.repository, oldRoot), ".docnexus/project.json")) !== undefined)) throw new DocNexusError("git_operation_failed", `another DocNexus project owns ${name}; do not overwrite its hook`);
      }
      if (action === "install" && !managed && await readIfExists(backup) !== undefined) throw new DocNexusError("git_operation_failed", `hook backup already exists: ${backup}; inspect it before installing`);
      items.push({ name, event, path, backup, existing, managed });
    }
    if (action === "status") return { installed: items.every(item => item.managed), repository: context.repository, hooks: items.map(item => ({ name: item.name, installed: item.managed })) };
    if (action !== "install" && action !== "uninstall") throw new DocNexusError("invalid_params", "Usage: docnexus git hooks install|status|uninstall");
    if (action === "install") await mkdir(directory, { recursive: true });
    for (const item of items) {
      if (action === "uninstall") {
        if (!item.managed && item.existing !== undefined) continue;
        if (item.managed) await rm(item.path);
        if (await readIfExists(item.backup) !== undefined) await rename(item.backup, item.path);
      } else {
        if (!item.managed && item.existing !== undefined) await rename(item.path, item.backup);
        const script = `#!/bin/sh
${MARKER}
${owner}
[ -n "$DOCNEXUS_GIT_INTERNAL" ] && exit 0
if [ -x "$0.docnexus-original" ]; then
  "$0.docnexus-original" "$@" || exit $?
fi
repository=$(pwd -P) || exit 1
project_relative=${quote(projectRelative)}
project=$(cd "$repository/$project_relative" 2>/dev/null && pwd -P) || exit 0
[ -f "$project/.docnexus/project.json" ] || exit 0
knowledge_changed=0
knowledge_diff() {
  git diff --cached --quiet --no-ext-diff --no-renames -- ${quote(`:(top,literal)${context.prefix}library/`)} ${quote(`:(top,literal)${context.prefix}records/`)}
}
git_index=$(git rev-parse --git-path index) || exit 1
if [ ${quote(item.event)} = index ] && [ -f "$git_index.lock" ]; then
  (export GIT_INDEX_FILE="$git_index.lock"; knowledge_diff) || knowledge_changed=$?
else
  knowledge_diff || knowledge_changed=$?
fi
if [ "$knowledge_changed" -gt 1 ]; then
  echo 'docnexus: cannot inspect staged knowledge; inspect the Git index before retrying.' >&2
  exit "$knowledge_changed"
fi
merge_head=$(git rev-parse --git-path MERGE_HEAD) || exit 1
has_merge=0
[ -f "$merge_head" ] && has_merge=1
if [ "$knowledge_changed" = 0 ] && [ "$has_merge" = 0 ]; then
  exit 0
fi
runtime_relative=${quote(runtimeRelative)}
runtime="$project/.docnexus/node_modules/@rowansenne/docnexus/dist/src/cli.js"
if [ ! -f "$runtime" ]; then runtime="$project/$runtime_relative"; fi
if [ ! -f "$runtime" ] || ! command -v node >/dev/null 2>&1 || ! node -e 'const [major,minor]=process.versions.node.split(".").map(Number);process.exit(major>22||(major===22&&minor>=13)?0:1)' >/dev/null 2>&1; then
  pending=''
  if [ "$has_merge" = 1 ]; then
    pending=$(git ls-files --unmerged --resolve-undo -- ${quote(`:(top,literal)${context.prefix}library/`)} ${quote(`:(top,literal)${context.prefix}records/`)}) || exit 1
  fi
  echo 'docnexus: local CLI or Node >=22.13 is unavailable; restore PATH and run npm ci --prefix ./.docnexus, or uninstall the DocNexus hooks.' >&2
  if [ ${quote(item.event)} = check ] && { [ "$knowledge_changed" != 0 ] || [ -n "$pending" ]; }; then exit 1; fi
  exit 0
fi
DOCNEXUS_GIT_HOOK=1 node "$runtime" --project-root "$project" git hook ${item.event} >/dev/null
`;
        await atomicWrite(item.path, script);
        await chmod(item.path, 0o755);
      }
    }
    return { installed: action === "install", repository: context.repository, hooks: Object.keys(hooks) };
  }, 30_000, { rejectPendingTransaction: true });
}
