import { atomicWrite, readIfExists } from "./workspace-io.js";
import { conceptIndexPath, conceptShardsPath, libraryRelativePath, WORKSPACE_DIRNAME, workspaceDirectory } from "./layout.js";
import { assertNoSymbolicLinks, listManagedDocuments, readRecordMetadata } from "./managed-documents.js";
import type { EntityType, RelationshipType } from "./types.js";
import { resolveKnowledge } from "./knowledge.js";
import { loadKnowledgeDocuments } from "./knowledge-service.js";
import { sha256 } from "./hash.js";

export interface ConceptEntry {
  name: string;
  type: EntityType;
  description: string;
  documents: string[];
  /** Categories of the documents that declare this concept. */
  categories: string[];
  relations: Array<{ type: RelationshipType; to: string }>;
  aliases?: string[];
}

export interface ConceptIndex {
  document_count: number;
  concept_count: number;
  categories: Array<{ name: string; document_count: number; concept_count: number }>;
  documents: Array<{ id: string; file_path: string; title: string; summary: string; category: string }>;
  concepts: ConceptEntry[];
}

const GENERATED_NOTICE = "<!-- Generated by docnexus; do not edit. Regenerated after every memory change. -->";
const UNCATEGORIZED = "uncategorized";
const MAX_DESCRIPTION_LENGTH = 160;
const MAX_LABEL_LENGTH = 40;
/** The root map is loaded into agent context, so it stays within a small fixed budget. */
const ROOT_BUDGET_BYTES = 3072;
/** Hard size limit for every generated category file; larger content is split by type and paged. */
const SHARD_BUDGET_BYTES = 32_000;
/** Per-line caps keep one heavily shared concept from filling a page. */
const MAX_LINE_DOCUMENTS = 10;
const MAX_LINE_RELATIONS = 10;
const MAX_LINE_LENGTH = 1500;
const SIGNPOST_STEPS = [6, 4, 2, 0];

function conceptKey(type: string, name: string): string {
  return `${type}:${name.trim().toLowerCase()}`;
}

/** Aggregates the entities and relationships declared across all records into one concept list. */
export async function buildConceptIndex(
  projectRoot: string,
  input: { type?: string; query?: string; category?: string } = {}
): Promise<ConceptIndex> {
  return withProjectLock(projectRoot, async () => {
    // Earliest documents win the display name and description of a shared concept, so output is stable.
    const records = (await listManagedDocuments(projectRoot))
      .sort((a, b) => a.created_at.localeCompare(b.created_at) || a.file_path.localeCompare(b.file_path));
    const concepts = new Map<string, ConceptEntry>();
    const documents: ConceptIndex["documents"] = [];
    const knowledge = resolveKnowledge(await loadKnowledgeDocuments(projectRoot));
    for (const record of records) {
      const metadata = knowledge.resolver.canonicalize(await readRecordMetadata(projectRoot, record.id));
      const category = metadata.category ?? UNCATEGORIZED;
      documents.push({ id: record.id, file_path: record.file_path, title: record.title, summary: record.summary, category });
      const byName = new Map<string, ConceptEntry>();
      for (const entity of metadata.entities) {
        const key = conceptKey(entity.type, entity.name);
        let entry = concepts.get(key);
        if (!entry) {
          entry = { name: entity.name.trim(), type: entity.type, description: entity.description.trim(), documents: [], categories: [], relations: [] };
          if (entity.aliases?.length) entry.aliases = entity.aliases;
          concepts.set(key, entry);
        }
        if (!entry.documents.includes(record.file_path)) entry.documents.push(record.file_path);
        if (!entry.categories.includes(category)) entry.categories.push(category);
        byName.set(entity.name.trim().toLowerCase(), entry);
      }
      for (const relationship of metadata.relationships) {
        const from = byName.get(relationship.from.trim().toLowerCase());
        if (from && !from.relations.some((value) => value.type === relationship.type && value.to === relationship.to.trim())) {
          from.relations.push({ type: relationship.type, to: relationship.to.trim() });
        }
      }
    }

    const query = input.query?.trim().toLowerCase();
    const list = [...concepts.values()]
      .filter((entry) => !input.type || entry.type === input.type)
      .filter((entry) => !input.category || entry.categories.includes(input.category))
      .filter((entry) => !query || [entry.name, entry.description, ...(entry.aliases ?? [])].some((name) => name.toLowerCase().includes(query)))
      .map((entry) => ({ ...entry, documents: entry.documents.sort(), categories: entry.categories.sort() }))
      .sort((a, b) => b.documents.length - a.documents.length || a.name.localeCompare(b.name));
    const shownDocuments = documents.filter((document) => !input.category || document.category === input.category);
    const categoryNames = [...new Set(shownDocuments.map((document) => document.category))];
    const categories = categoryNames
      .map((name) => ({
        name,
        document_count: shownDocuments.filter((document) => document.category === name).length,
        concept_count: list.filter((entry) => entry.categories.includes(name)).length
      }))
      .sort((a, b) => b.document_count - a.document_count || a.name.localeCompare(b.name));
    return { document_count: shownDocuments.length, concept_count: list.length, categories, documents: shownDocuments, concepts: list };
  });
}

function truncate(value: string, length: number): string {
  return value.length > length ? `${value.slice(0, length - 1)}…` : value;
}

function documentLine(document: ConceptIndex["documents"][number], projectRoot?: string): string {
  return truncate(`- **${document.title}** — ${truncate(document.summary, MAX_DESCRIPTION_LENGTH)} → \`${libraryRelativePath(document.file_path, projectRoot)}\``, MAX_LINE_LENGTH);
}

function capped(items: string[], limit: number, more: (count: number) => string): string[] {
  return items.length > limit ? [...items.slice(0, limit), more(items.length - limit)] : items;
}

function conceptLine(entry: ConceptEntry, limitLists = false, projectRoot?: string): string {
  let relations = entry.relations.map((relation) => `${relation.type} ${relation.to}`);
  let documents = entry.documents.map((path) => `\`${libraryRelativePath(path, projectRoot)}\``);
  if (limitLists) {
    relations = capped(relations, MAX_LINE_RELATIONS, (count) => `${count} more`);
    documents = capped(documents, MAX_LINE_DOCUMENTS, (count) => `${count} more: \`docnexus concepts --query "${entry.name}"\``);
  }
  const line = `- **${entry.name}**${entry.aliases?.length ? ` (${entry.aliases.join(", ")})` : ""} — ${truncate(entry.description, MAX_DESCRIPTION_LENGTH)}${relations.length ? ` (${relations.join("; ")})` : ""} → ${documents.join(", ")}`;
  return limitLists ? truncate(line, MAX_LINE_LENGTH) : line;
}

function conceptSections(concepts: ConceptEntry[], limitLists = false, projectRoot?: string): string[] {
  const lines: string[] = [];
  for (const type of [...new Set(concepts.map((entry) => entry.type))].sort()) {
    lines.push(`## ${type}`, "", ...concepts.filter((entry) => entry.type === type).map((entry) => conceptLine(entry, limitLists, projectRoot)), "");
  }
  return lines;
}

/** Full, uncapped listing of documents and concepts, grouped by entity type. */
export function renderConceptListing(index: ConceptIndex, projectRoot?: string): string {
  const lines = ["# DocNexus concepts", "", `${index.document_count} document(s) and ${index.concept_count} concept(s).`, ""];
  if (index.documents.length > 0) lines.push("## Documents", "", ...index.documents.map(document => documentLine(document, projectRoot)), "");
  if (index.concepts.length === 0) lines.push(index.document_count === 0 ? "_No concepts._" : "_No named concepts. Read the documents above._", "");
  else lines.push(...conceptSections(index.concepts, false, projectRoot));
  return lines.join("\n");
}

/**
 * Assigns each category a stable, filesystem-safe file name. Names that collide after normalization,
 * or that are reserved on Windows, carry a hash of the exact category so the mapping never depends on order.
 */
export function categoryFileNames(categories: string[]): Map<string, string> {
  const base = (name: string) => name.normalize("NFKC").toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "category";
  const counts = new Map<string, number>();
  for (const name of categories) counts.set(base(name), (counts.get(base(name)) ?? 0) + 1);
  return new Map(categories.map((name) => {
    const slug = base(name);
    const unique = counts.get(slug) === 1 && !/^(con|prn|aux|nul|com\d|lpt\d)$/.test(slug);
    return [name, unique ? slug : `${slug}-${sha256(name).slice(0, 8)}`];
  }));
}

function tableCell(value: string): string {
  return truncate(value, MAX_LABEL_LENGTH).replace(/\|/g, "\\|").replace(/`/g, "'");
}

function shardHeader(category: string, index: ConceptIndex, concepts: ConceptEntry[], page?: string, projectRoot?: string): string[] {
  const documentCount = index.documents.filter((document) => document.category === category).length;
  return [
    `# DocNexus concepts: ${category}${page ? ` — ${page}` : ""}`,
    "",
    GENERATED_NOTICE,
    "",
    `Category \`${category}\` holds ${documentCount} document(s) and ${concepts.length} concept(s). Concepts shared with other categories list all their documents.`,
    `Narrow retrieval to this domain with \`--category "${category}"\`. Other categories are listed in \`${projectRoot ? workspaceDirectory(projectRoot) : WORKSPACE_DIRNAME}/CONCEPTS.md\`.`,
    ""
  ];
}

const bytes = (lines: string[]) => Buffer.byteLength(lines.join("\n"));

/** Greedily packs lines into pages whose rendered size, including the fixed lines, stays within budget. */
function paginate(lines: string[], fixedBytes: number, budget = SHARD_BUDGET_BYTES): string[][] {
  const pages: string[][] = [];
  let current: string[] = [];
  let size = fixedBytes;
  for (const line of lines) {
    const added = Buffer.byteLength(line) + 1;
    if (current.length > 0 && size + added > budget) {
      pages.push(current);
      current = [];
      size = fixedBytes;
    }
    current.push(line);
    size += added;
  }
  if (current.length > 0) pages.push(current);
  return pages;
}

function renderShards(index: ConceptIndex, category: string, slug: string, projectRoot?: string): Map<string, string> {
  const documents = index.documents.filter((document) => document.category === category);
  const concepts = index.concepts.filter((entry) => entry.categories.includes(category));
  const header = shardHeader(category, index, concepts, undefined, projectRoot);
  const documentSection = documents.length > 0 ? ["## Documents", "", ...documents.map(document => documentLine(document, projectRoot)), ""] : [];
  const single = [...header, ...documentSection, ...(concepts.length > 0 ? conceptSections(concepts, true, projectRoot) : ["_No named concepts. Read the documents above._", ""])].join("\n");
  if (Buffer.byteLength(single) <= SHARD_BUDGET_BYTES) return new Map([[`concepts/${slug}.md`, single]]);

  // Oversized domains keep a hub with documents and links to type pages, each page within the same budget.
  const files = new Map<string, string>();
  const links: string[] = [];
  for (const type of [...new Set(concepts.map((entry) => entry.type))].sort()) {
    const entries = concepts.filter((entry) => entry.type === type);
    const lines = entries.map((entry) => conceptLine(entry, true, projectRoot));
    const fixed = bytes([...shardHeader(category, index, concepts, `${type} page 0000 of 0000`, projectRoot), `## ${type}`, "", ""]);
    const pages = paginate(lines, fixed);
    let first = 1;
    pages.forEach((page, number) => {
      const name = number === 0 ? `${type}.md` : `${type}-${number + 1}.md`;
      const label = pages.length > 1 ? `${type} page ${number + 1} of ${pages.length}` : type;
      files.set(`concepts/${slug}/${name}`, [...shardHeader(category, index, concepts, label, projectRoot), `## ${type}`, "", ...page, ""].join("\n"));
      links.push(`- ${type} ${first}–${first + page.length - 1} of ${entries.length} → \`${projectRoot ? workspaceDirectory(projectRoot) : WORKSPACE_DIRNAME}/concepts/${slug}/${name}\``);
      first += page.length;
    });
  }
  const typeSection = links.length > 0 ? ["## Concepts by type", "", ...links, ""] : [];
  const overflow = (count: number) => `_${count} more document(s): run \`docnexus document query --category "${category}"\`._`;
  const fixed = bytes([...header, "## Documents", "", overflow(documents.length), "", ...typeSection]) + 1;
  const lines = documents.map(document => documentLine(document, projectRoot));
  const shown = lines.length > 0 && fixed + Buffer.byteLength(lines[0]) + 1 <= SHARD_BUDGET_BYTES ? paginate(lines, fixed)[0] : [];
  const hub = [...header];
  if (documents.length > 0) {
    hub.push("## Documents", "", ...shown);
    if (shown.length < documents.length) hub.push(overflow(documents.length - shown.length));
    hub.push("");
  }
  hub.push(...typeSection);
  files.set(`concepts/${slug}.md`, hub.join("\n"));
  return files;
}

/** Short routing map loaded into agent context: one row per category, never the full index. */
export function renderConceptIndex(index: ConceptIndex, projectRoot?: string): string {
  const intro = [
    "# DocNexus concepts",
    "",
    GENERATED_NOTICE,
    ""
  ];
  if (index.document_count === 0) {
    return [...intro, "_No project memory yet. Capture project knowledge with the `docnexus` skill._", ""].join("\n");
  }
  intro.push(
    `Project memory holds ${index.document_count} document(s) and ${index.concept_count} concept(s) in ${index.categories.length} categor${index.categories.length === 1 ? "y" : "ies"}.`,
    "This is a short map, not the full index. Decide from the task itself whether memory matters: a topic missing here may still be stored, so never skip `docnexus-recall` because of this map.",
    "Open a category file to list that domain completely or to find canonical names and aliases; run `docnexus concepts --query <term>` for an exact concept lookup.",
    ""
  );
  const names = categoryFileNames(index.categories.map((category) => category.name));
  const row = (category: ConceptIndex["categories"][number], signposts: number) => {
    const key = index.concepts
      .filter((entry) => entry.categories.includes(category.name))
      .map((entry) => ({ entry, uses: entry.documents.filter((path) => index.documents.some((document) => document.file_path === path && document.category === category.name)).length }))
      .sort((a, b) => b.uses - a.uses || a.entry.name.localeCompare(b.entry.name))
      .slice(0, signposts)
      .map(({ entry }) => tableCell(entry.name));
    return `| ${tableCell(category.name)} | ${category.document_count} | ${category.concept_count} | ${key.join(", ")} | \`${projectRoot ? workspaceDirectory(projectRoot) : WORKSPACE_DIRNAME}/concepts/${names.get(category.name)}.md\` |`;
  };
  const render = (rows: string[], omitted: number) => [
    ...intro,
    "| Category | Docs | Concepts | Key concepts | File |",
    "| --- | ---: | ---: | --- | --- |",
    ...rows,
    ...(omitted > 0 ? ["", `_${omitted} more categor${omitted === 1 ? "y" : "ies"} in \`${projectRoot ? workspaceDirectory(projectRoot) : WORKSPACE_DIRNAME}/concepts/\`._`] : []),
    ""
  ].join("\n");
  for (const signposts of SIGNPOST_STEPS) {
    const markdown = render(index.categories.map((category) => row(category, signposts)), 0);
    if (Buffer.byteLength(markdown) <= ROOT_BUDGET_BYTES) return markdown;
  }
  const rows = index.categories.map((category) => row(category, 0));
  let shown = rows.length;
  while (shown > 0 && Buffer.byteLength(render(rows.slice(0, shown), rows.length - shown)) > ROOT_BUDGET_BYTES) shown -= 1;
  return render(rows.slice(0, shown), rows.length - shown);
}

/** Every generated concept file, keyed by its path relative to the workspace. */
export function renderConceptFiles(index: ConceptIndex, projectRoot?: string): Map<string, string> {
  const files = new Map<string, string>([["CONCEPTS.md", renderConceptIndex(index, projectRoot)]]);
  const names = categoryFileNames(index.categories.map((category) => category.name));
  for (const category of index.categories) {
    for (const [path, content] of renderShards(index, category.name, names.get(category.name)!, projectRoot)) files.set(path, content);
  }
  return files;
}

async function listGeneratedShards(directory: string, prefix: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true }).catch((error: NodeJS.ErrnoException) => {
    if (error.code === "ENOENT") return [];
    throw error;
  });
  const files: string[] = [];
  for (const entry of entries) {
    if (entry.isDirectory()) files.push(...await listGeneratedShards(join(directory, entry.name), `${prefix}${entry.name}/`));
    else if (entry.isFile() && entry.name.endsWith(".md")) files.push(`${prefix}${entry.name}`);
  }
  return files;
}

async function removeEmptyDirectories(directory: string, keepRoot: boolean): Promise<void> {
  const entries = await readdir(directory, { withFileTypes: true }).catch(() => undefined);
  if (!entries) return;
  for (const entry of entries) if (entry.isDirectory()) await removeEmptyDirectories(join(directory, entry.name), false);
  if (!keepRoot && (await readdir(directory)).length === 0) await rmdir(directory);
}

export async function writeConceptIndex(projectRoot: string): Promise<void> {
  return withProjectLock(projectRoot, async () => {
    const files = renderConceptFiles(await buildConceptIndex(projectRoot), projectRoot);
    const shardsRoot = conceptShardsPath(projectRoot);
    await assertNoSymbolicLinks(projectRoot, join(workspaceDirectory(projectRoot), "concepts"));
    for (const path of files.keys()) await assertNoSymbolicLinks(projectRoot, join(workspaceDirectory(projectRoot), ...path.split("/")));
    // Only files carrying the generated notice are removed, so hand-placed files survive.
    for (const path of await listGeneratedShards(shardsRoot, "concepts/")) {
      if (files.has(path)) continue;
      const absolute = join(workspaceDirectory(projectRoot), ...path.split("/"));
      await assertNoSymbolicLinks(projectRoot, absolute);
      if ((await readIfExists(join(projectRoot, absolute)))?.includes(GENERATED_NOTICE)) await rm(join(projectRoot, absolute), { force: true });
    }
    if (await lstat(shardsRoot).then((info) => info.isDirectory(), () => false)) await removeEmptyDirectories(shardsRoot, false);
    // Shards first, then the root map, so the map never points at a file that is not written yet.
    const ordered = [...files.keys()].filter((path) => path !== "CONCEPTS.md").sort().concat("CONCEPTS.md");
    for (const path of ordered) {
      const absolute = path === "CONCEPTS.md" ? conceptIndexPath(projectRoot) : join(shardsRoot, ...path.split("/").slice(1));
      const content = files.get(path)!;
      if ((await readIfExists(absolute)) !== content) await atomicWrite(absolute, content);
    }
  });
}
